    static final int RAIL = 64;
    static final ToIntBiFunction<Integer, Integer> NO_WATER = (x, z) -> Integer.MIN_VALUE;

    static List<TrackCell> straight(int from, int to, boolean east, CellKind kind) {
        List<TrackCell> cells = new ArrayList<>();
        for (int i = from; i <= to; i++) cells.add(new TrackCell(east ? i : 0, RAIL, east ? 0 : i, kind));
        return cells;
    }
    /** East for 12 cells, a raster S-curve north-east, then a ramp east. */
    static List<TrackCell> mixed(CellKind kind) {
        List<TrackCell> cells = new ArrayList<>();
        int x = 0, z = 0, y = RAIL;
        for (int i = 0; i < 12; i++) cells.add(new TrackCell(x++, y, z, kind));
        for (int i = 0; i < 4; i++) { cells.add(new TrackCell(x, y, z, kind)); z++; cells.add(new TrackCell(x, y, z, kind)); x++; }
        for (int i = 0; i < 6; i++) cells.add(new TrackCell(x++, y, z, kind));
        for (int i = 0; i < 6; i++) cells.add(new TrackCell(x++, ++y, z, kind));
        for (int i = 0; i < 6; i++) cells.add(new TrackCell(x++, y, z, kind));
        return cells;
    }
    static Map<RealisticTrack.Voxel, BlockOp> byVoxel(List<BlockOp> ops) {
        Map<RealisticTrack.Voxel, BlockOp> map = new HashMap<>();
        for (BlockOp op : ops) assertNull(map.put(RealisticTrack.Voxel.of(op), op), "duplicate " + op);
        return map;
    }
    static List<BlockOp> realistic(List<TrackCell> cells, ToIntBiFunction<Integer, Integer> ground, ToIntBiFunction<Integer, Integer> water, CellWorks.Settings s) {
        return RealisticTrack.segment(cells, ground, ground, water, s);
    }
    static String sha(List<BlockOp> ops) throws Exception {
        var digest = MessageDigest.getInstance("SHA-256");
        for (BlockOp op : ops) digest.update((op.toString() + "\n").getBytes(StandardCharsets.UTF_8));
        return HexFormat.of().formatHex(digest.digest());
    }

    @Test void classicStyleIsTheUnchangedFactoryOutputAndItsGoldenHashIsPinned() throws Exception {
        var settings = CellWorks.Settings.defaults();
        ToIntBiFunction<Integer, Integer> hills = (x, z) -> 60 + Math.floorMod(x * 7 + z * 3, 9);
        for (CellKind kind : CellKind.values()) {
            var cells = kind == CellKind.PLATFORM ? straight(0, 30, true, kind) : mixed(kind);
            assertEquals(Factory.segment(cells, hills, hills, NO_WATER, settings), TrackStyle.CLASSIC.segment(cells, hills, hills, NO_WATER, settings));
        }
        // Pinned before the realistic layer was added: Factory/CellWorks must keep producing exactly this plan,
        // because the approved mainline export and older quotes were generated by this code.
        var pinned = Factory.segment(mixed(CellKind.GROUND), hills, hills, NO_WATER, settings);
        assertEquals(GOLDEN_CLASSIC, sha(pinned) + "/" + pinned.size());
        var mainlineSettings = new CellWorks.Settings(6, 4, 12, false, 3, 6);
        var bridge = Factory.segment(mixed(CellKind.BRIDGE), (x, z) -> 50, (x, z) -> 48, (x, z) -> 55, mainlineSettings);
        assertEquals(GOLDEN_MAINLINE_BRIDGE, sha(bridge) + "/" + bridge.size());
    }
    static final String GOLDEN_CLASSIC = "588798d4fd003557fa4246b6d4010bc666768e8b271bc7e267d12c20c8e3e781/913";
    static final String GOLDEN_MAINLINE_BRIDGE = "24ed5b1bfd5f755c943ffce062d5a041a76aedd8cc8ff907642e1274b66f34fd/1182";

