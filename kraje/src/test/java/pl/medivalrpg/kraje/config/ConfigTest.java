package pl.medivalrpg.kraje.config;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.logging.Logger;
import net.kyori.adventure.text.Component;
import net.kyori.adventure.text.minimessage.tag.resolver.Placeholder;
import net.kyori.adventure.text.serializer.plain.PlainTextComponentSerializer;
import org.bukkit.configuration.file.YamlConfiguration;
import org.junit.jupiter.api.Test;
import pl.medivalrpg.kraje.model.Rank;
import pl.medivalrpg.kraje.protection.ProtectionService;
import pl.medivalrpg.kraje.protection.PvpRules;

class ConfigTest {

    private static YamlConfiguration load() {
        return YamlConfiguration.loadConfiguration(new InputStreamReader(
            ConfigTest.class.getResourceAsStream("/config.yml"), StandardCharsets.UTF_8));
    }

    private static String plain(final Component c) {
        return PlainTextComponentSerializer.plainText().serialize(c);
    }

    @Test
    void defaultsMatchSpecification() {
        final KrajeConfig cfg = new KrajeConfig(load());
        assertEquals(16, cfg.claimsBase);
        assertEquals(8, cfg.claimsPerMember);
        assertEquals(24, cfg.claimLimit(1));
        assertEquals(3, cfg.foundMinDistanceChunks);
        assertEquals(300_000L, cfg.inviteExpiryMillis);
        assertEquals("", cfg.mapUrl);
        assertEquals(0.55, cfg.mapFillOpacity);
        assertEquals(40, cfg.mapRefreshDebounceTicks);
        assertTrue(cfg.protection.enabled);
        assertFalse(cfg.protection.explosions);
        assertTrue(cfg.tablistEnabled);
        assertTrue(cfg.chatEnabled);
        assertEquals(12, cfg.defaultColors.size());
        assertTrue(cfg.rankIcon(Rank.RULER).contains("♛"));
    }

    @Test
    void newKeysDefaults() {
        final KrajeConfig cfg = new KrajeConfig(load());
        assertEquals(PvpRules.Mode.VANILLA, cfg.pvp.mode(), "default: normal PvP everywhere");
        assertTrue(cfg.pvp.friendlyFire());
        assertEquals(500, cfg.foundCost);
        assertEquals(50, cfg.claimCostBase);
        assertEquals(2, cfg.upkeepPerChunk);
        assertEquals(3, cfg.graceDays);
        assertEquals(java.time.LocalTime.of(18, 0), cfg.dailyTickTime);
        assertEquals(120 * 60_000L, cfg.warMinDurationMillis);
        assertEquals(30 * 60_000L, cfg.siegeMaxDurationMillis);
        assertEquals(Rank.ADVISOR, cfg.siegeMinRank);
        assertTrue(cfg.siegeAllowedActions.contains(ProtectionService.Flag.BLOCK_BREAK));
        assertFalse(cfg.siegeAllowedActions.contains(ProtectionService.Flag.CONTAINERS));
        assertTrue(cfg.siegeExcludedBlocks.contains("#shulker_boxes"));
        assertFalse(cfg.npcPlayersCanJoin);
        assertTrue(cfg.mapExportJson);
        assertEquals("block.note_block.chime", cfg.borderSoundEnter);
    }

    /** The server's config.yml was generated by the old version: new keys must come from the jar's defaults. */
    @Test
    void oldServerConfigUsesJarDefaultsForNewKeys() {
        final YamlConfiguration server = new YamlConfiguration();
        server.set("claims.base", 20);
        server.set("pvp.mode", "war-only");
        server.set("economy.found-cost", 999);
        final YamlConfiguration jar = load();
        jar.set("siege.cost", 777); // proves the value is read from the defaults, not from the code fallback
        server.setDefaults(jar);
        final KrajeConfig cfg = new KrajeConfig(server);
        assertEquals(20, cfg.claimsBase);
        assertEquals(PvpRules.Mode.WAR_ONLY, cfg.pvp.mode());
        assertEquals(999, cfg.foundCost);
        assertEquals(777, cfg.siegeCost);
        assertEquals(300, cfg.claimsMax);
        assertEquals(0.25, cfg.claimsPerNpcCitizen);
    }

    @Test
    void claimLimitWithPopulationAndCap() {
        final KrajeConfig cfg = new KrajeConfig(load());
        // 16 + 8 × 3 players + floor(0.25 × 9) = 16 + 24 + 2
        final KrajeConfig.ClaimLimit limit = cfg.claimLimitFor(3, 9);
        assertEquals(42, limit.total());
        assertEquals(2, limit.fromPopulation());
        assertFalse(limit.capped());
        // NPC country: no players, only base + population
        assertEquals(16 + 25, cfg.claimLimitFor(0, 100).total());
        // hard cap
        final KrajeConfig.ClaimLimit big = cfg.claimLimitFor(50, 1000);
        assertEquals(300, big.total());
        assertTrue(big.capped());
        assertEquals(24, cfg.claimLimit(1), "old method unchanged");
        // claims.max: 0 = no cap
        final YamlConfiguration yaml = load();
        yaml.set("claims.max", 0);
        assertEquals(16 + 8 * 50 + 250, new KrajeConfig(yaml).claimLimitFor(50, 1000).total());
    }

    @Test
    void npcPlannerGetsExtraLandAboveTheLimit() {
        final KrajeConfig cfg = new KrajeConfig(load());
        assertEquals(64, cfg.claimsNpcPlannerBonus);
        final KrajeConfig.ClaimLimit npc = cfg.claimLimitFor(0, 100);
        assertEquals(16 + 25 + 64, cfg.npcPlannerLimit(npc), "normal limit + bonus");
        final KrajeConfig.ClaimLimit capped = cfg.claimLimitFor(0, 100_000);
        assertEquals(300 + 64, cfg.npcPlannerLimit(capped), "the bonus goes beyond claims.max");
        final YamlConfiguration yaml = load();
        yaml.set("claims.npc-planner-bonus", -1);
        assertEquals(Integer.MAX_VALUE, new KrajeConfig(yaml).npcPlannerLimit(npc), "-1 = no limit");
    }

    @Test
    void allMessagesParse() {
        final YamlConfiguration yaml = load();
        final Messages messages = new Messages(yaml, Logger.getAnonymousLogger());
        final var section = yaml.getConfigurationSection("messages");
        for (final String key : section.getKeys(true)) {
            if (!section.isString(key)) {
                continue;
            }
            final Component c = messages.get(key,
                Placeholder.unparsed("country", "Aldoria"), Placeholder.unparsed("player", "Gracz"));
            assertFalse(plain(c).contains("<prefix>"), key);
        }
    }

    @Test
    void usageArgumentsStayLiteral() {
        final Messages messages = new Messages(load(), Logger.getAnonymousLogger());
        assertEquals("[Kraje] Użycie: /kraj zaloz <nazwa>", plain(messages.get("usage-zaloz")));
        assertTrue(plain(messages.get("usage-kolor")).contains("<#RRGGBB|nazwa>"));
    }

    @Test
    void userInputIsNotParsed() {
        final Messages messages = new Messages(load(), Logger.getAnonymousLogger());
        final Component c = messages.get("joined", Placeholder.unparsed("country", "<red>Zły</red>"),
            Placeholder.styling("color", net.kyori.adventure.text.format.NamedTextColor.GOLD));
        assertTrue(plain(c).contains("<red>Zły</red>"));
    }
}
