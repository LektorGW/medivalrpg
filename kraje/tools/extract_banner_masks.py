"""Extracts the alpha masks of the vanilla banner patterns for the vanilla-banner approximation of country flags.

Reads the Minecraft client jar (e.g. plugins/BetterModel/.cache/26.3.jar), takes the banner cloth front face of every
pattern texture (assets/minecraft/textures/entity/banner/<id>.png, region x 1..20, y 1..40 of the 64x64 texture — the
front face of BannerFlagModel: texOffs(0,0), addBox(-10, 0, -2, 20, 40, 1)) and stores ONLY the alpha channel (the
geometric shape of the pattern, no colours or texture art). Patterns: those of data/minecraft/tags/banner_pattern/
no_item_required.json (loom without a pattern item) plus "base". Also stores the mean cloth shade of base.png.

Usage: python extract_banner_masks.py <client.jar> <out.txt>
"""
import base64, io, json, os, sys, zipfile
from PIL import Image

W, H, X0, Y0 = 20, 40, 1, 1

def main(jar_path, out_path):
    with zipfile.ZipFile(jar_path) as jar:
        tag = json.loads(jar.read('data/minecraft/tags/banner_pattern/no_item_required.json'))
        ids = ['base'] + [v.split(':', 1)[1] for v in tag['values']]
        lines = ['# Copyright (c) 2026 Maciej Kaczmarczyk — lektoro.pl',
                 '# Alpha masks of the vanilla banner patterns (20x40 front face), generated by kraje/tools/extract_banner_masks.py',
                 '# from ' + os.path.basename(jar_path) + '. Format: <pattern id> <base64 of 800 alpha bytes, row-major>.']
        shade = None
        for pid in ids:
            im = Image.open(io.BytesIO(jar.read(f'assets/minecraft/textures/entity/banner/{pid}.png'))).convert('RGBA')
            assert im.size == (64, 64), (pid, im.size)
            alpha = bytes(im.getpixel((X0 + x, Y0 + y))[3] for y in range(H) for x in range(W))
            if pid == 'base':
                greys = [im.getpixel((X0 + x, Y0 + y))[0] for y in range(H) for x in range(W)]
                shade = sum(greys) / len(greys) / 255.0
            lines.append(pid + ' ' + base64.b64encode(alpha).decode('ascii'))
        lines.insert(3, f'shade {shade:.4f}')
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(len(ids), 'patterns, shade', round(shade, 4))

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
